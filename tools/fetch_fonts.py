#!/usr/bin/env python3
"""Self-host the heading typeface (Noto Serif TC / SC, weight 500) as unicode-range slices.

Run from the repo root when the font version should be refreshed:  python tools/fetch_fonts.py
Writes fonts/<family>-<version>/*.woff2 and css/fonts.css (bundled into css/site.css by
tools/build_site_ui.mjs). Browsers download only the slices that contain characters shown on
the page, so a heading costs a few small files rather than a whole CJK font.

One static weight (500) is declared for the range 400-700: every heading, card title and the
brand mark render at the same weight, and the browser never synthesises a fake bold.
Noto Serif is licensed under the SIL Open Font License 1.1 (fonts/OFL.txt).
"""
import pathlib, re, shutil, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/130.0 Safari/537.36")
FAMILIES = [("Noto Serif TC", "NZ Serif TC", "noto-serif-tc"),
            ("Noto Serif SC", "NZ Serif SC", "noto-serif-sc")]


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


out_css = ["/* Generated by tools/fetch_fonts.py - do not edit. Noto Serif, SIL OFL 1.1. */"]
total = 0
for family, alias, slug in FAMILIES:
    css = get("https://fonts.googleapis.com/css2?family=" + family.replace(" ", "+")
              + ":wght@500&display=swap").decode("utf-8")
    faces = re.findall(r"@font-face\s*\{(.*?)\}", css, re.S)
    version = re.search(r"/s/[a-z]+/(v\d+)/", css).group(1)
    folder = ROOT / "fonts" / f"{slug}-{version}"
    for old in (ROOT / "fonts").glob(f"{slug}-*"):
        if old != folder:
            shutil.rmtree(old)
    folder.mkdir(parents=True, exist_ok=True)
    for i, face in enumerate(faces):
        url = re.search(r"url\((https://[^)]+\.woff2)\)", face).group(1)
        rng = re.search(r"unicode-range:\s*([^;]+);", face).group(1).strip()
        target = folder / f"{i:03d}.woff2"
        if not target.exists():
            target.write_bytes(get(url))
        total += target.stat().st_size
        out_css.append(
            f"@font-face{{font-family:'{alias}';font-style:normal;font-weight:400 700;font-display:swap;"
            f"src:url(/fonts/{folder.name}/{target.name}) format('woff2');unicode-range:{rng}}}")
    print(f"{family}: {len(faces)} slices -> fonts/{folder.name}")

(ROOT / "css").mkdir(exist_ok=True)
(ROOT / "css" / "fonts.css").write_text("\n".join(out_css) + "\n", encoding="utf-8", newline="\n")
lic = ROOT / "fonts" / "OFL.txt"
if not lic.exists():
    lic.write_bytes(get("https://raw.githubusercontent.com/notofonts/noto-cjk/main/Serif/LICENSE"))
print(f"total {total / 1048576:.1f} MiB; wrote css/fonts.css")
